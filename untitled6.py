import osmnx as ox
import networkx as nx
import matplotlib.pyplot as plt

# Configuración de robustez para evitar caídas por saturación del servidor principal de Overpass
ox.settings.timeout = 180           # Incrementar el tiempo de espera a 180 segundos
ox.settings.requests_timeout = 180  # Tiempo de espera para peticiones HTTP

# Usar un servidor alternativo público de Overpass más estable en este momento
ox.settings.overpass_endpoint = "https://overpass.kumi.systems/api/interpreter"

# Coordenada central del campus (Latitud, Longitud)
centro_campus = (4.7835, -74.0425)

print(f"🔄 Descargando la red vial/peatonal del campus alrededor de {centro_campus}...")
try:
    # Descargamos el grafo usando un punto central y un radio de 600 metros
    G = ox.graph_from_point(centro_campus, dist=600, network_type="all")
except Exception as e:
    print(f"⚠️ Error con servidor alternativo 1: {e}")
    print("Probando con servidor alternativo 2 (Francia)...")
    try:
        ox.settings.overpass_endpoint = "https://overpass.openstreetmap.ru/api/interpreter"
        G = ox.graph_from_point(centro_campus, dist=600, network_type="all")
    except Exception as e2:
        print(f"⚠️ Error persistente: {e2}")
        print("Los servidores públicos de OpenStreetMap están saturados en este momento. Inténtalo de nuevo en unos minutos.")
        raise e2

# Definir dos puntos geográficos (Latitud, Longitud) dentro del campus para encontrar una ruta
# Origen: Entrada peatonal por la Autopista Norte
origen_coords = (4.7828, -74.0434)
# Destino: Edificio interno del campus (Bloque de laboratorios/aulas)
destino_coords = (4.7839, -74.0415)

# Encontrar los nodos de la red más cercanos a nuestras coordenadas
origen_node = ox.nearest_nodes(G, X=origen_coords[1], Y=origen_coords[0])
destino_node = ox.nearest_nodes(G, X=destino_coords[1], Y=destino_coords[0])

# Calcular la ruta más corta basada en la longitud de las calles (peso='length')
print("🧮 Calculando la ruta más corta dentro del campus...")
ruta = nx.shortest_path(G, origen_node, destino_node, weight="length")

# Graficar la red del campus y superponer la ruta calculada
print("🎨 Generando el mapa del campus...")
fig, ax = ox.plot_graph_route(
    G,
    ruta,
    route_color="cyan",
    route_linewidth=4,
    node_size=0,          # Oculta los nodos generales para limpiar la vista
    edge_color="#333333",
    edge_linewidth=1.2,
    bgcolor="#111111"     # Fondo oscuro estilo modo noche
)